def show_formulas(rows):
    for name, tex, note in rows:
        c1, c2 = st.columns([1, 2])
        c1.markdown(f"**{name}**" + (f"  \n<span style='color:gray;font-size:.85em'>{note}</span>" if note else ""),
                    unsafe_allow_html=True)
        c2.latex(tex)


